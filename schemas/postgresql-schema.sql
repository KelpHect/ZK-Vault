-- 4.1 Append-only mutation blocker (for immutable ledger & revision tables)
CREATE OR REPLACE FUNCTION vault.prevent_immutable_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, vault
AS $$
BEGIN
    RAISE EXCEPTION
        'APPEND_ONLY_VIOLATION: % on immutable table %.% is strictly prohibited',
        TG_OP, TG_TABLE_SCHEMA, TG_TABLE_NAME
        USING ERRCODE = '42501';
END;
$$;

-- 4.2 Automatic `updated_at` timestamp maintenance for mutable control tables
CREATE OR REPLACE FUNCTION vault.touch_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, vault
AS $$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

