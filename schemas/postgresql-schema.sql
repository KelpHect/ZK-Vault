CREATE TABLE vault.tenants (
    tenant_id                 UUID                  NOT NULL,
    slug                      TEXT                  NOT NULL,
    display_name              TEXT                  NOT NULL,
    status                    vault.tenant_status   NOT NULL DEFAULT 'provisioning',
    default_cipher_suite      SMALLINT              NOT NULL DEFAULT 1,
    escrow_tier               vault.escrow_tier     NOT NULL DEFAULT 'enterprise_escrow', -- Tenant default escrow tier
    orpk_public_key           BYTEA,                -- Nullable strictly when escrow_tier = 'strict_zk'
    orpk_epoch                INTEGER               NOT NULL DEFAULT 1,
    drpk_public_key           BYTEA,
    drpk_epoch                INTEGER,
    compliance_public_key     BYTEA                 NOT NULL,
    compliance_key_epoch      INTEGER               NOT NULL DEFAULT 1,
    blind_epoch               INTEGER               NOT NULL DEFAULT 1,
    root_manifest_cbor        BYTEA                 NOT NULL,
    root_manifest_version     BIGINT                NOT NULL DEFAULT 1,
    root_manifest_signature   BYTEA                 NOT NULL,
    max_graph_depth           SMALLINT              NOT NULL DEFAULT 4,
    created_at                TIMESTAMPTZ           NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ           NOT NULL DEFAULT now(),
    shredded_at               TIMESTAMPTZ,

    CONSTRAINT pk_tenants
        PRIMARY KEY (tenant_id),
    CONSTRAINT uq_tenants_slug
        UNIQUE (slug),
    CONSTRAINT chk_tenants_slug_format
        CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$'),
    CONSTRAINT chk_tenants_cipher_suite
        CHECK (default_cipher_suite IN (1, 2)),
    CONSTRAINT chk_tenants_epochs_positive
        CHECK (
            orpk_epoch >= 1
            AND compliance_key_epoch >= 1
            AND blind_epoch >= 1
            AND root_manifest_version >= 1
            AND (drpk_epoch IS NULL OR drpk_epoch >= 1)
        ),
    CONSTRAINT chk_tenants_orpk_required_unless_strict_zk
        CHECK (escrow_tier = 'strict_zk' OR orpk_public_key IS NOT NULL),
    CONSTRAINT chk_tenants_drpk_required_for_standard
        CHECK (
            (escrow_tier = 'standard' AND drpk_public_key IS NOT NULL AND drpk_epoch IS NOT NULL)
            OR (escrow_tier <> 'standard')
        ),
    CONSTRAINT chk_tenants_max_graph_depth
        CHECK (max_graph_depth BETWEEN 1 AND 4),
    CONSTRAINT chk_tenants_key_lengths
        CHECK (
            (orpk_public_key IS NULL OR octet_length(orpk_public_key) BETWEEN 32 AND 2048)
            AND octet_length(compliance_public_key) BETWEEN 32 AND 2048
            AND (drpk_public_key IS NULL OR octet_length(drpk_public_key) BETWEEN 32 AND 2048)
        )
);

CREATE TRIGGER trg_tenants_touch_updated_at
    BEFORE UPDATE ON vault.tenants
    FOR EACH ROW
    EXECUTE FUNCTION vault.touch_updated_at();

