                EXECUTE format(
                    'CREATE TRIGGER %I '
                    'BEFORE TRUNCATE ON vault.%I '
                    'FOR EACH STATEMENT '
                    'EXECUTE FUNCTION vault.prevent_immutable_mutation()',
                    'trg_' || v_part_name || '_no_truncate',
                    v_part_name
                );
            END IF;
        END LOOP;
    END LOOP;
END
$$;

