-- -----------------------------------------------------------------------------
-- 8. Blind Structural DAG Validation Trigger (Cycles & MAX_GRAPH_DEPTH = 4)
-- -----------------------------------------------------------------------------
-- Enforces acyclicity and bounded team nesting depth on `team_to_team` edges
-- at the database layer as defense-in-depth alongside `rsv-graph`.
CREATE OR REPLACE FUNCTION vault.validate_team_dag_edge()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, vault
AS $$
DECLARE
    v_max_depth        SMALLINT;
    v_cycle_found      BOOLEAN;
    v_ancestor_depth   INTEGER;
    v_descendant_depth INTEGER;
    v_lock_key         BIGINT;
BEGIN
    IF NEW.edge_type <> 'team_to_team' OR NEW.status <> 'active' THEN
        RETURN NEW;
    END IF;

    -- Serialize team-to-team topology mutations per tenant to prevent
    -- concurrent READ COMMITTED cycle insertion anomalies (A->B || B->A).
    v_lock_key := hashtextextended('rsv:graph:dag:' || NEW.tenant_id::text, 0);
    PERFORM pg_advisory_xact_lock(v_lock_key);

    SELECT t.max_graph_depth
      INTO v_max_depth
      FROM vault.tenants t
     WHERE t.tenant_id = NEW.tenant_id;

    IF v_max_depth IS NULL THEN
        RAISE EXCEPTION 'TENANT_MISMATCH: unknown tenant %', NEW.tenant_id
            USING ERRCODE = 'P0001';
    END IF;

    -- 1. Cycle check: verify NEW.source_id is NOT reachable from NEW.target_id.
    WITH RECURSIVE reachable(node_id, depth) AS (
        SELECT NEW.target_id, 1
        UNION ALL
        SELECT e.target_id, r.depth + 1
          FROM reachable r
          JOIN vault.key_graph_edges e
            ON e.tenant_id = NEW.tenant_id
           AND e.edge_type = 'team_to_team'
           AND e.status = 'active'
           AND e.edge_id <> NEW.edge_id
           AND e.source_id = r.node_id
         WHERE r.depth <= v_max_depth + 1
    )
    SELECT EXISTS (
        SELECT 1 FROM reachable WHERE node_id = NEW.source_id
    ) INTO v_cycle_found;

    IF v_cycle_found THEN
        RAISE EXCEPTION
            'GRAPH_CYCLE_REJECTED: inserting team_to_team edge % -> % introduces a cycle',
            NEW.source_id, NEW.target_id
            USING ERRCODE = 'P0001';
    END IF;

    -- 2. Bounded depth check: longest ancestor chain to source_id + 1 +
    --    longest descendant chain from target_id MUST be <= v_max_depth.
    WITH RECURSIVE ancestors(node_id, depth) AS (
        SELECT NEW.source_id, 0
        UNION ALL
        SELECT e.source_id, a.depth + 1
          FROM ancestors a
          JOIN vault.key_graph_edges e
            ON e.tenant_id = NEW.tenant_id
           AND e.edge_type = 'team_to_team'
           AND e.status = 'active'
           AND e.edge_id <> NEW.edge_id
           AND e.target_id = a.node_id
         WHERE a.depth < v_max_depth
    )
    SELECT COALESCE(MAX(depth), 0) INTO v_ancestor_depth FROM ancestors;

    WITH RECURSIVE descendants(node_id, depth) AS (
        SELECT NEW.target_id, 0
        UNION ALL
        SELECT e.target_id, d.depth + 1
          FROM descendants d
          JOIN vault.key_graph_edges e
            ON e.tenant_id = NEW.tenant_id
           AND e.edge_type = 'team_to_team'
           AND e.status = 'active'
           AND e.edge_id <> NEW.edge_id
           AND e.source_id = d.node_id
         WHERE d.depth < v_max_depth
    )
    SELECT COALESCE(MAX(depth), 0) INTO v_descendant_depth FROM descendants;

    IF (v_ancestor_depth + 1 + v_descendant_depth) > v_max_depth THEN
        RAISE EXCEPTION
            'GRAPH_CYCLE_REJECTED: team_to_team depth % exceeds MAX_GRAPH_DEPTH (%)',
            (v_ancestor_depth + 1 + v_descendant_depth), v_max_depth
            USING ERRCODE = 'P0001';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_key_graph_edges_validate_dag
    BEFORE INSERT OR UPDATE OF source_id, target_id, edge_type, status
    ON vault.key_graph_edges
    FOR EACH ROW
    EXECUTE FUNCTION vault.validate_team_dag_edge();

