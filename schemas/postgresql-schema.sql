--              adrs/ADR-0011-stream-chunked-aead-and-fido-cxf.md
--
-- Design Invariants:
--   1. Shared-schema multi-tenancy inside schema `vault` (17 canonical tables:
--      12 core tables + 5 extension tables for Key Transparency, Blind SCIM,
--      OIDC Machine Identities, and STREAM Encrypted Attachments).
--   2. Every table, primary key, unique index, secondary index, and foreign key
--      leads with `tenant_id UUID NOT NULL` for composite isolation and locality.
--   3. High-cardinality tables (7 of 17) use `PARTITION BY HASH (tenant_id)`
--      with 64 child partitions (`p00`..`p63`, 448 total partitions) for bounded
--      B-tree depth, autovacuum concurrency, and O(1) partition pruning.
--   4. Every table enables BOTH `ENABLE ROW LEVEL SECURITY` AND
--      `FORCE ROW LEVEL SECURITY` with InitPlan-cached LEAKPROOF `uuid_eq`
--      predicates tied to transaction-local GUC `app.current_tenant_id`.
--   5. Application runtime role `rsv_app` and read-only compliance role
--      `rsv_auditor_ro` are strictly `NOSUPERUSER NOBYPASSRLS`.
--   6. Immutable ledger & revision tables (`vault.audit_events`,
--      `vault.audit_merkle_tiles`, `vault.audit_checkpoints`,
--      `vault.key_transparency_log`, `vault.key_transparency_checkpoints`, and
--      `vault.vault_item_revisions`) enforce append-only immutability via
--      triggers blocking UPDATE/DELETE and privilege revocation on TRUNCATE.
--   7. UUIDv7 identifiers are generated by the application/client (`rsv-types`)
--      so this DDL executes cleanly on both PostgreSQL 17 and PostgreSQL 18
--      (PostgreSQL 18 deployments MAY additionally use native `uuidv7()` in
--      operational utilities).
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Roles (Idempotent Provisioning — Strictly Least-Privilege)
-- -----------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rsv_migrator') THEN
        CREATE ROLE rsv_migrator
            NOLOGIN
            NOSUPERUSER
            NOCREATEDB
            NOCREATEROLE
            NOINHERIT
            NOREPLICATION
            NOBYPASSRLS;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rsv_app') THEN
        CREATE ROLE rsv_app
            NOLOGIN
            NOSUPERUSER
            NOCREATEDB
            NOCREATEROLE
            NOINHERIT
            NOREPLICATION
            NOBYPASSRLS;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rsv_auditor_ro') THEN
        CREATE ROLE rsv_auditor_ro
            NOLOGIN
            NOSUPERUSER
            NOCREATEDB
            NOCREATEROLE
            NOINHERIT
            NOREPLICATION
            NOBYPASSRLS;
    END IF;

    -- Dedicated zero-privilege owner for pre-auth slug -> tenant_id resolution.
    -- Receives column-level SELECT (tenant_id, slug, status) on vault.tenants ONLY.
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rsv_slug_resolver') THEN
        CREATE ROLE rsv_slug_resolver
            NOLOGIN
            NOSUPERUSER
            NOCREATEDB
            NOCREATEROLE
            NOINHERIT
            NOREPLICATION
            NOBYPASSRLS;
    END IF;
END
$$;

-- -----------------------------------------------------------------------------
-- 2. Schema Creation & Search-Path Hygiene
-- -----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS vault AUTHORIZATION rsv_migrator;

REVOKE ALL ON SCHEMA vault FROM PUBLIC;
GRANT USAGE ON SCHEMA vault TO rsv_app, rsv_auditor_ro, rsv_slug_resolver;
GRANT ALL ON SCHEMA vault TO rsv_migrator;

SET LOCAL search_path = vault, pg_catalog;

