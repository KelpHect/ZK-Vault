-- Table 2/17: vault.tenant_vss_ceremonies
-- =============================================================================
CREATE TABLE vault.tenant_vss_ceremonies (
    tenant_id                 UUID                     NOT NULL,
    ceremony_id               UUID                     NOT NULL,
    ceremony_type             vault.vss_ceremony_type  NOT NULL,
    orpk_epoch                INTEGER                  NOT NULL,
    cipher_suite              SMALLINT                 NOT NULL DEFAULT 1,
    threshold_k               SMALLINT                 NOT NULL DEFAULT 3,
    total_shares_n            SMALLINT                 NOT NULL DEFAULT 5,
    feldman_commitments       BYTEA                    NOT NULL, -- Custodian-encrypted Feldman commitments CBOR (ADR-0001 HNDL mitigation; plaintext curve points NEVER stored in DB)
    commitment_digest         BYTEA                    NOT NULL, -- SHA-256 digest over canonical plaintext Feldman commitments for public verification
    public_key_derived        BYTEA                    NOT NULL,
    trustee_attestations      JSONB                    NOT NULL DEFAULT '[]'::jsonb,
    status                    vault.ceremony_status    NOT NULL DEFAULT 'pending',
    initiated_by_user_id      UUID                     NOT NULL,
    created_at                TIMESTAMPTZ              NOT NULL DEFAULT now(),
    finalized_at              TIMESTAMPTZ,

    CONSTRAINT pk_tenant_vss_ceremonies
        PRIMARY KEY (tenant_id, ceremony_id),
    CONSTRAINT fk_vss_ceremonies_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES vault.tenants (tenant_id),
    CONSTRAINT chk_vss_cipher_suite
        CHECK (cipher_suite IN (1, 2)),
    CONSTRAINT chk_vss_quorum_bounds
        CHECK (threshold_k >= 2 AND total_shares_n >= threshold_k AND total_shares_n <= 32),
    CONSTRAINT chk_vss_orpk_epoch
        CHECK (orpk_epoch >= 1),
    CONSTRAINT chk_vss_commitment_digest_len
        CHECK (octet_length(commitment_digest) = 32),
    CONSTRAINT chk_vss_attestations_array
        CHECK (jsonb_typeof(trustee_attestations) = 'array'),
    CONSTRAINT chk_vss_finalized_ts
        CHECK (status <> 'finalized' OR finalized_at IS NOT NULL)
);

CREATE INDEX idx_vss_ceremonies_tenant_epoch
    ON vault.tenant_vss_ceremonies (tenant_id, orpk_epoch DESC, created_at DESC);

CREATE UNIQUE INDEX uq_vss_ceremonies_finalized_epoch
