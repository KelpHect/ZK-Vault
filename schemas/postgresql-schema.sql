-- -----------------------------------------------------------------------------
-- 10. Row-Level Security (ENABLE + FORCE RLS on ALL 17 Tables)
-- -----------------------------------------------------------------------------
-- Policy predicate uses a scalar subselect InitPlan:
--   `tenant_id = (SELECT NULLIF(current_setting('app.current_tenant_id', true), '')::uuid)`
-- Why:
--   1. The scalar subselect evaluates `current_setting` + `::uuid` ONCE per
--      statement as an InitPlan parameter `$0` (not once per scanned row).
--   2. Row filtering reduces strictly to `uuid_eq(tenant_id, $0)`, a built-in
--      LEAKPROOF operator, eliminating error-oracle side channels and enabling
--      index condition pushdown.
--   3. When `app.current_tenant_id` is unset or empty, `NULLIF` returns NULL,
--      and `tenant_id = NULL` evaluates to UNKNOWN (fail-closed: zero rows).
DO $$
DECLARE
    v_table  TEXT;
    v_tables TEXT[] := ARRAY[
        'tenants',
        'tenant_vss_ceremonies',
        'users',
        'user_devices',
        'teams',
        'collections',
        'key_graph_edges',
        'vault_items',
        'vault_item_revisions',
        'audit_events',
        'audit_merkle_tiles',
        'audit_checkpoints',
        'key_transparency_log',
        'key_transparency_checkpoints',
        'scim_pending_intents',
        'machine_identities',
        'vault_attachments'
    ];
BEGIN
    FOREACH v_table IN ARRAY v_tables LOOP
        EXECUTE format('ALTER TABLE vault.%I ENABLE ROW LEVEL SECURITY', v_table);
        EXECUTE format('ALTER TABLE vault.%I FORCE ROW LEVEL SECURITY', v_table);

        EXECUTE format(
            'CREATE POLICY %I ON vault.%I '
            'AS PERMISSIVE '
            'FOR ALL '
            'TO rsv_app, rsv_auditor_ro, rsv_migrator '
            'USING (tenant_id = (SELECT NULLIF(current_setting(''app.current_tenant_id'', true), '''')::uuid)) '
            'WITH CHECK (tenant_id = (SELECT NULLIF(current_setting(''app.current_tenant_id'', true), '''')::uuid))',
            'pol_' || v_table || '_tenant_isolation',
            v_table
        );
    END LOOP;
END
$$;

