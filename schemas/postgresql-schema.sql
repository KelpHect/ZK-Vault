                'CREATE TABLE vault.%I PARTITION OF vault.%I '
                'FOR VALUES WITH (MODULUS 64, REMAINDER %s)',
                v_part_name,
                v_table,
                v_part_idx
            );

            -- Attach statement-level TRUNCATE guard directly on leaf partitions
            -- of immutable tables (PostgreSQL disallows TRUNCATE triggers on
            -- partitioned parent tables).
